//! 監査ログの `prev_hash` 鎖に署名付きチェックポイントを足す下書き（ADR 0007）。
//!
//! - [`chain`]：04 の `audit_events` 行（actor、subject、操作、結果、snapshot hash、
//!   policy版、日時、prev_hash）の下書きと、workspace 内の線形ハッシュ鎖の計算・歩査。
//! - [`note`]：C2SP signed-note の署名形式の最小実装（Ed25519 のみ）。
//! - [`checkpoint`]：鎖の最新ハッシュと行数に署名したチェックポイントの作成・検証。
//!
//! # 守ること（この crate が表す不変条件）
//!
//! - チェックポイントは鎖の「行数」と「その行数までの最新ハッシュ」にだけ署名する。
//! - 検証は (1) 署名の検証、(2) 本文の形式、(3) origin（workspace ごとの鎖の識別子）
//!   の一致、(4) 鎖の歩査（保存済みハッシュの付き合わせ）、(5) 行数と最新ハッシュの
//!   照合の順で行い、どれか 1 つでも失敗したら検証失敗として扱う。
//! - DB の管理者が鎖全体を書き換えて再計算しても、保管済みチェックポイントとの
//!   不一致として検出できる。ただし最新チェックポイントより後の追記分は次の
//!   チェックポイントまで担保されない（定期発行が前提）。
//! - 署名鍵を DB の管理者が握れば検出できなくなる（署名者だけが触れられる場所に
//!   置く。ADR 0007）。
//!
//! 確定したスキーマではない。PostgreSQL への組み込み・保管先の運用は製品設計で決める。

#![forbid(unsafe_code)]

pub mod chain;
pub mod checkpoint;
pub mod note;
